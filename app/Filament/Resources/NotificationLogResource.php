<?php

namespace App\Filament\Resources;

use App\Filament\Resources\NotificationLogResource\Pages;
use App\Models\NotificationLog;
use App\Services\Notifications\MsegatSmsService;
use Filament\Forms;
use Filament\Infolists;
use Filament\Notifications\Notification;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\HtmlString;

class NotificationLogResource extends Resource
{
    protected static ?string $model = NotificationLog::class;
    protected static bool $shouldRegisterNavigation = false;
    protected static ?string $navigationIcon = 'heroicon-o-clipboard-document-list';
    protected static ?string $navigationGroup = 'Logs';
    protected static ?int $navigationSort = 1;
    protected static ?string $navigationLabel = 'All Notification Logs';
    protected static ?string $modelLabel = 'Notification Log';
    protected static ?string $pluralModelLabel = 'Notification Logs';

    public static function canViewAny(): bool
    {
        return auth()->user()?->hasPermission('notification_logs') ?? true;
    }

    public static function canCreate(): bool
    {
        return false; // Logs are automatically generated by the system
    }

    public static function table(Table $table): Table
    {
        return $table
            ->defaultSort('id', 'desc')
            ->columns([
                Tables\Columns\TextColumn::make('id')
                    ->label('#')
                    ->sortable(),

                Tables\Columns\TextColumn::make('channel')
                    ->label('Channel')
                    ->badge()
                    ->formatStateUsing(fn (string $state) => strtoupper($state))
                    ->color(fn (string $state): string => match ($state) {
                        'email' => 'info',
                        'sms' => 'warning',
                        default => 'gray',
                    })
                    ->icon(fn (string $state): string => match ($state) {
                        'email' => 'heroicon-o-envelope',
                        'sms' => 'heroicon-o-chat-bubble-left-right',
                        default => 'heroicon-o-bell',
                    }),

                Tables\Columns\TextColumn::make('status')
                    ->label('Status')
                    ->badge()
                    ->formatStateUsing(fn (string $state) => ucfirst($state))
                    ->color(fn (string $state): string => match ($state) {
                        'sent' => 'success',
                        'failed' => 'danger',
                        default => 'gray',
                    })
                    ->icon(fn (string $state): string => match ($state) {
                        'sent' => 'heroicon-o-check-circle',
                        'failed' => 'heroicon-o-x-circle',
                        default => 'heroicon-o-question-mark-circle',
                    }),

                Tables\Columns\TextColumn::make('event_key')
                    ->label('Trigger Event')
                    ->badge()
                    ->color('primary')
                    ->searchable(),

                Tables\Columns\TextColumn::make('recipient')
                    ->label('Recipient')
                    ->searchable()
                    ->copyable()
                    ->tooltip('Click to copy'),

                Tables\Columns\TextColumn::make('subject_or_sender')
                    ->label('Subject / Sender')
                    ->limit(35)
                    ->tooltip(fn (NotificationLog $record) => $record->subject_or_sender),

                Tables\Columns\TextColumn::make('error_message')
                    ->label('Error Detail')
                    ->limit(40)
                    ->color('danger')
                    ->placeholder('None')
                    ->tooltip(fn (NotificationLog $record) => $record->error_message),

                Tables\Columns\TextColumn::make('created_at')
                    ->label('Dispatched At')
                    ->dateTime('d M Y, h:i:s A')
                    ->sortable(),
            ])
            ->filters([
                Tables\Filters\SelectFilter::make('channel')
                    ->label('Channel')
                    ->options([
                        'email' => 'Email',
                        'sms' => 'SMS',
                    ]),

                Tables\Filters\SelectFilter::make('status')
                    ->label('Status')
                    ->options([
                        'sent' => 'Sent Successfully',
                        'failed' => 'Failed Delivery',
                    ]),

                Tables\Filters\SelectFilter::make('event_key')
                    ->label('Event Key')
                    ->options(fn () => NotificationLog::distinct()->pluck('event_key', 'event_key')->toArray()),
            ])
            ->actions([
                Tables\Actions\Action::make('view_details')
                    ->label('View Log')
                    ->icon('heroicon-o-eye')
                    ->color('info')
                    ->modalHeading(fn (NotificationLog $record) => 'Notification Log #' . $record->id . ' Details')
                    ->modalWidth('4xl')
                    ->infolist([
                        Infolists\Components\Section::make('Delivery Summary')
                            ->schema([
                                Infolists\Components\Grid::make(4)
                                    ->schema([
                                        Infolists\Components\TextEntry::make('channel')
                                            ->label('Channel')
                                            ->badge()
                                            ->color(fn (string $state): string => $state === 'email' ? 'info' : 'warning'),

                                        Infolists\Components\TextEntry::make('status')
                                            ->label('Status')
                                            ->badge()
                                            ->color(fn (string $state): string => $state === 'sent' ? 'success' : 'danger'),

                                        Infolists\Components\TextEntry::make('event_key')
                                            ->label('Event')
                                            ->badge(),

                                        Infolists\Components\TextEntry::make('created_at')
                                            ->label('Timestamp')
                                            ->dateTime('d M Y, h:i:s A'),
                                    ]),

                                Infolists\Components\Grid::make(3)
                                    ->schema([
                                        Infolists\Components\TextEntry::make('recipient')
                                            ->label('Recipient')
                                            ->copyable(),

                                        Infolists\Components\TextEntry::make('subject_or_sender')
                                            ->label('Subject / Sender'),

                                        Infolists\Components\TextEntry::make('ip_address')
                                            ->label('IP Address')
                                            ->placeholder('N/A'),
                                    ]),
                            ]),

                        Infolists\Components\Section::make('Error Details (سبب الفشل)')
                            ->schema([
                                Infolists\Components\TextEntry::make('error_message')
                                    ->label('Exception / Gateway Error')
                                    ->color('danger')
                                    ->extraAttributes(['class' => 'font-mono text-xs text-red-600 bg-red-50 p-3 rounded-lg border border-red-200']),
                            ])
                            ->visible(fn (NotificationLog $record) => !empty($record->error_message)),

                        Infolists\Components\Section::make('Dispatched Content (محتوى الرسالة)')
                            ->schema([
                                Infolists\Components\ViewEntry::make('content_preview')
                                    ->label('')
                                    ->view('filament.components.notification-preview'),
                            ]),
                    ]),

                Tables\Actions\Action::make('resend')
                    ->label('Resend')
                    ->icon('heroicon-o-arrow-path')
                    ->color('warning')
                    ->requiresConfirmation()
                    ->modalHeading('Resend Notification')
                    ->modalDescription(fn (NotificationLog $record) => "Are you sure you want to re-dispatch this {$record->channel} to {$record->recipient}?")
                    ->action(function (NotificationLog $record, MsegatSmsService $smsService) {
                        try {
                            if ($record->channel === 'sms') {
                                $result = $smsService->send(
                                    $record->recipient,
                                    $record->content,
                                    'retry_' . $record->event_key
                                );

                                if ($result['success']) {
                                    Notification::make()
                                        ->title('SMS Resent Successfully!')
                                        ->success()
                                        ->send();
                                } else {
                                    Notification::make()
                                        ->title('SMS Resend Failed')
                                        ->body($result['message'])
                                        ->danger()
                                        ->send();
                                }
                            } else {
                                Mail::html($record->content, function ($msg) use ($record) {
                                    $msg->to($record->recipient)
                                        ->subject($record->subject_or_sender ?: 'Grass Florist Notification');
                                });

                                NotificationLog::create([
                                    'channel' => 'email',
                                    'event_key' => 'retry_' . $record->event_key,
                                    'recipient' => $record->recipient,
                                    'subject_or_sender' => $record->subject_or_sender,
                                    'content' => $record->content,
                                    'status' => 'sent',
                                    'error_message' => null,
                                ]);

                                Notification::make()
                                    ->title('Email Resent Successfully!')
                                    ->success()
                                    ->send();
                            }
                        } catch (\Throwable $e) {
                            Notification::make()
                                ->title('Resend Exception')
                                ->body($e->getMessage())
                                ->danger()
                                ->send();
                        }
                    }),

                Tables\Actions\DeleteAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListNotificationLogs::route('/'),
        ];
    }
}
